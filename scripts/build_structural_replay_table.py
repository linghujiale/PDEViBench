#!/usr/bin/env python3
"""SI Note 3 structural-variant table (Nature/generated/nmi_structural_replay_table.tex)."""
import csv
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SR = ROOT / "analysis/round1_review_20261029/structural_replay"
OUT = ROOT / "Nature/generated/nmi_structural_replay_table.tex"
FAM = {"heterogeneous_diffusion": "Heterogeneous diffusion", "advection_diffusion_reaction": "Advection--diffusion--reaction",
       "lshape_poisson": "L-shaped Poisson", "coupled_elliptic": "Coupled elliptic"}
VAR = {"coef_contrast_up": "Coefficient contrast raised", "coef_contrast_inverted": "Coefficient contrast inverted",
       "advection_direction_31": "Advection direction changed", "diffusivity_31": "Diffusivity raised",
       "reaction_31": "Reaction rate raised", "corner_moved_10_15": "Re-entrant corner moved",
       "coupling_strong": "Coupling strengthened", "coef_contrast": "Coefficient contrast changed"}
spec = list(csv.DictReader((SR / "structural_spec_summary.csv").open()))
corr = SR / "lshape_corrected_spec_summary.csv"
if corr.exists():
    c = {r["perturbation"]: r for r in csv.DictReader(corr.open())}
    spec = [c.get(r["perturbation"], r) if r["family"] == "lshape_poisson" else r for r in spec]
pc = list(csv.DictReader((SR / "structural_replay_pass_counts_by_spec.csv").open()))
rows = []
for fam in FAM:
    for r in [x for x in spec if x["family"] == fam and x["primary"] == "True"]:
        ag = [x for x in pc if x["family"] == fam and x["label"] == r["perturbation"] and x["who"].startswith("codex")]
        af = [x for x in pc if x["family"] == fam and x["label"] == r["perturbation"] and x["who"] == "negative_affine_reconstruction"]
        rows.append(f"{FAM[fam]} & {VAR[r['perturbation']]} & {float(r['best_affine_min']):.3f} & {float(r['ratio_min']):.2f} & "
                    f"{sum(int(x['n_pass']) for x in ag)}/{sum(int(x['n']) for x in ag)} & {sum(int(x['n_pass']) for x in af)}/{sum(int(x['n']) for x in af)} \\\\")
OUT.write_text("% Generated by scripts/build_structural_replay_table.py; do not edit.\n\\newcommand{\\NMIStructuralReplayRows}{%\n" + "\n".join(rows) + "\n}\n")
print("\n".join(rows))
