#!/usr/bin/env python3
"""Build the route-test tables of Supplementary Note 1."""
import csv
from collections import Counter
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
A = list(csv.DictReader((ROOT / "analysis/reaudit_20261030/reaudit_90_programs.csv").open()))
X = list(csv.DictReader((ROOT / "analysis/reaudit_20261030/reaudit_relabels_20261030.csv").open()))
assert len(A) == 90 and len(X) == 42
assert all(r["reaudit_verdict"] == "NUMERICAL" for r in A)
con = [r for r in A if r["group"] == "contested"]; assert len(con) == 47
uses = Counter(t for r in con for t in set(r["target_uses"].split(";")))
cons = Counter(c for r in X for c in r["constructs"].split("; "))
ORDER = ["spectral or modal basis (DST/FFT/eigendecomposition)",
         "second component as 0.5 times the solved first component (linearity)",
         "exact time integration of the semi-discrete system",
         "separation of variables on the single angular mode of the forcing",
         "Richardson extrapolation of discrete solves",
         "Taylor start with the discrete Laplacian",
         "finite-difference or IMEX time stepping with stated u0 and MMS forcing",
         "unexecuted exact-solution fallback branch"]
LABEL = {ORDER[0]: "Sine-transform, Fourier or eigenfunction basis",
         ORDER[1]: "Second component of a vector target as 0.5 times the first (linearity)",
         ORDER[2]: "Exact time integration of the semi-discrete system",
         ORDER[3]: "Separation of variables on the single angular mode of the forcing",
         ORDER[4]: "Richardson extrapolation of two discrete solves",
         ORDER[5]: "Taylor start with the discrete Laplacian",
         ORDER[6]: "Finite-difference or IMEX time stepping",
         ORDER[7]: "Exact-solution fallback branch, not executed"}
assert set(cons) <= set(ORDER), set(cons) - set(ORDER)
rows = [f"Closed-form target used to build the forcing & {uses['forcing_only']} \\\\",
        f"Stated initial state used as initial data & {uses['initial_condition']} \\\\"]
rows2 = [f"{LABEL[k]} & {cons[k]} \\\\" for k in ORDER if cons[k]]
exp = Counter(r["experiment_id"] for r in X)
out = ["% Generated by scripts/build_reaudit_si_table.py; do not edit.",
       "\\newcommand{\\NMIReauditContestedRows}{%", *rows, "}",
       "\\newcommand{\\NMIReauditAgreedRows}{%", *rows2, "}",
       f"\\newcommand{{\\NMIReauditContestedCount}}{{{len(con)}}}",
       f"\\newcommand{{\\NMIReauditAgreedCount}}{{{len(X)}}}"]
D = ROOT / "analysis/reaudit_20261030"
T = list(csv.DictReader((D / "perturbation_route_test_90_numbers.csv").open()))
K = list(csv.DictReader((D / "perturbation_route_test_calibration40_numbers.csv").open()))
V = list(csv.DictReader((D / "adversarial_calibration5.csv").open()))
assert len(T) == 90 and len(K) == 40 and len(V) == 5
def thr(r): return max(0.01, 10 * float(r["e0"]))
for r in T:
    if float(r["e_v"]) <= thr(r):
        assert r["route_test_class_final"] == "follows"
    else:
        assert r["route_test_class_final"] == "instance_specific" and float(r["e_v_in"]) <= thr(r)
OUT3 = ["follows", "instance_specific", "target"]
def kcls(r):
    return "target" if r["rule"].startswith("target") else r["rule"]
KIND = {"route_valid": "Numerical (sampled passes)", "direct_recovery": "Direct reconstruction", "mixed_route": "Mixed return"}
cal = Counter((r["ledger_route"], kcls(r)) for r in K)
cal_rows = [f"{KIND[k]} & {sum(cal[(k, o)] for o in OUT3)} & {cal[(k, 'follows')]} & {cal[(k, 'instance_specific')]} & {cal[(k, 'target')]} \\\\"
            for k in ["route_valid", "direct_recovery", "mixed_route"]]
adv = Counter(r["final_class"] for r in V)
cal_rows.append(f"Constructed target-derived programs & 5 & {adv['follows']} & {adv['instance_specific']} & {adv['target']} \\\\")
reads = sum(1 for r in K if r["ledger_route"] != "route_valid" and r["reads_data"] == "yes")
EXP = [("phase2_wave1_codex", "Primary panel, Codex, original prompt"), ("phase2_wave1b_claude", "Prohibition rerun, Claude Code"),
       ("phase2_wave1b_openrouter", "Prohibition rerun, DeepSeek V3.2"), ("axis1024_claude", "Breadth panel, Claude Code"),
       ("scaffold64_minimalguide", "Minimal guide"), ("pcsep128_prescriptionguide", "Prescription-only guide"),
       ("pcsep128_nocodeguide", "Choice-free guide")]
exp_rows = []
for key, lab in EXP:
    rs = [r for r in T if r["experiment_id"].startswith(key)]
    hum = sum(r["human_consensus"] != "NUMERICAL_SOLVER" for r in rs)
    gen = sum(r["route_test_class_final"] == "follows" for r in rs)
    exp_rows.append(f"{lab} & {len(rs)} & {hum} & {gen} & {len(rs) - gen} & 0 \\\\")
assert sum(int(x.split(" & ")[1]) for x in exp_rows) == 90
inst = Counter(r["structure"] for r in T if r["route_test_class_final"] != "follows")
agreed = [r for r in T if r["group"] == "agreed_invalid"]; contested = [r for r in T if r["group"] == "contested"]
SLAB = {"ratio": "component ratio", "mode": "single angular mode", "timeform": "forcing time form", "layout": "x--y symmetry"}
def sci(x):
    x = float(x)
    if x == 0: return "0"
    m_, e_ = f"{x:.1e}".split("e"); return f"${m_}\\times10^{{{int(e_)}}}$"
ist = sorted([r for r in T if r["route_test_class_final"] != "follows"], key=lambda r: (r["structure"], r["experiment_id"], r["blind_id"]))
ELAB = dict(EXP)
inst_rows = [f"{r['blind_id']} & {[v for k, v in EXP if r['experiment_id'].startswith(k)][0].split(', ')[-1].replace(' guide', '').lower()} & {SLAB[r['structure']]} & {sci(r['e0'])} & {sci(r['e_v'])} & {sci(r['e_u'])} & {sci(r['e_v_in'])} & {sci(r['e_u_in'])} & {r['ref_class']} \\\\" for r in ist]
gf = {lab: sum(r["route_test_class_final"] == "follows" for r in T if r["experiment_id"].startswith(k)) for k, lab in EXP}
out += ["\\newcommand{\\NMIRouteTestCalibrationRows}{%", *cal_rows, "}",
        "\\newcommand{\\NMIRouteTestExperimentRows}{%", *exp_rows, "}",
        "\\newcommand{\\NMIRouteTestInstanceRows}{%", *inst_rows, "}",
        f"\\newcommand{{\\NMIRouteTestFollowCount}}{{{sum(r['route_test_class_final'] == 'follows' for r in T)}}}",
        f"\\newcommand{{\\NMIRouteTestInstanceSpecificCount}}{{{sum(inst.values())}}}",
        f"\\newcommand{{\\NMIRouteTestRatioCount}}{{{inst['ratio']}}}",
        f"\\newcommand{{\\NMIRouteTestModeCount}}{{{inst['mode']}}}",
        f"\\newcommand{{\\NMIRouteTestTimeCount}}{{{inst['timeform']}}}",
        f"\\newcommand{{\\NMIRouteTestLayoutCount}}{{{inst['layout']}}}",
        f"\\newcommand{{\\NMIRouteTestAgreedFollowCount}}{{{sum(r['route_test_class_final'] == 'follows' for r in agreed)}}}",
        f"\\newcommand{{\\NMIRouteTestAgreedInstanceCount}}{{{sum(r['route_test_class_final'] != 'follows' for r in agreed)}}}",
        f"\\newcommand{{\\NMIRouteTestContestedFollowCount}}{{{sum(r['route_test_class_final'] == 'follows' for r in contested)}}}",
        f"\\newcommand{{\\NMIRouteTestCalibReadsDataCount}}{{{reads}}}",
        f"\\newcommand{{\\NMIRouteTestChoiceFreeInstanceCount}}{{{14 - gf['Choice-free guide']}}}",
        f"\\newcommand{{\\NMIRouteTestMinimalInstanceCount}}{{{26 - gf['Minimal guide']}}}"]
(ROOT / "Nature/generated/nmi_reaudit_si_table.tex").write_text("\n".join(out) + "\n")
print(uses, cons, exp)
