#!/usr/bin/env python3
"""Primary-panel rates over calls on faithful specifications."""
import csv
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
L = [r for r in csv.DictReader((ROOT / "analysis/nmi_phase5_20260813/final_postreview_route_ledger.csv").open())
     if r["experiment_id"].startswith("phase2_wave1_codex")]
I = list(csv.DictReader((ROOT / "analysis/benchmark_integrity_report.csv").open()))
sign = {r["case_id"] for r in I if "forcing_representation" in r.get("failed_checks", "")}
masked = {r["case_id"] for r in L if r["tau_acc"] == ""}
F = [r for r in L if r["case_id"] not in sign and r["case_id"] not in masked]
n = len(F); ep = sum(r["endpoint_pass"] == "True" for r in F); rv = sum(r["route_status"] == "route_valid" for r in F)
sign_cases = len({r["case_id"] for r in L if r["case_id"] in sign}); masked_cases = len(masked)
assert len(L) == 1450 and sign_cases == 10 and masked_cases == 20 and n == 1300, (len(L), sign_cases, masked_cases, n)
m = {"NMIFaithfulCallCount": f"{n:,}", "NMIFaithfulEndpointCount": f"{ep:,}", "NMIFaithfulClaimSupportingCount": f"{rv:,}",
     "NMIFaithfulEndpointRate": f"{100*ep/n:.2f}\\%", "NMIFaithfulClaimSupportingRate": f"{100*rv/n:.2f}\\%",
     "NMIFaithfulGapPP": f"{100*(ep-rv)/n:.2f}", "NMIUnfaithfulCallCount": f"{1450-n}"}
E = [r for r in csv.DictReader((ROOT / "paper/source_data/fig_program_aware_score_and_robustness/fig2_factor_effects.csv").open())
     if r["estimand"] == "route_valid_minus_endpoint" and r["term"] == "D"][0]
m.update({"NMIFigTwoDDifference": f"{float(E['estimate']):.3f}", "NMIFigTwoDDifferenceCILow": f"{float(E['ci95_low']):.3f}",
          "NMIFigTwoDDifferenceCIHigh": f"{float(E['ci95_high']):.3f}"})
out = ["% Generated by scripts/build_faithful_rates.py; do not edit."] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
(ROOT / "Nature/generated/nmi_faithful_rates_macros.tex").write_text("\n".join(out) + "\n")
print(m)
