#!/usr/bin/env python3
"""Source data for the prompt comparison: same agent and 290 cases under the original and the prohibition prompt.
"""
from __future__ import annotations
import csv, json
from collections import defaultdict
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "analysis/nmi_phase5_20260813/final_postreview_route_ledger.csv"
OUT = ROOT / "paper/source_data/fig3_exact_formula_audit"
W1 = "phase2_wave1_codex_scipy_20260522T030958Z"
W1B = "phase2_wave1b_codex_scipy_no_exact_20260523T224200Z"
FAMILY_ORDER = ["Poisson", "Helmholtz_low_k", "heat", "wave", "linear_elasticity", "Burgers"]

rows = list(csv.DictReader(LEDGER.open(newline="", encoding="utf-8")))
per_case = {W1: defaultdict(lambda: [0, 0, 0]), W1B: defaultdict(lambda: [0, 0, 0])}
family = {}
for r in rows:
    if r["experiment_id"] in per_case:
        c = per_case[r["experiment_id"]][r["case_id"]]
        c[2] += 1
        c[0] += r["endpoint_pass"] == "True"
        c[1] += r["route_status"] == "route_valid"
        family[r["case_id"]] = r["family"]
cases = sorted(per_case[W1])
assert cases == sorted(per_case[W1B]) and len(cases) == 290

table = []
for fam in FAMILY_ORDER + ["All"]:
    sel = [c for c in cases if fam == "All" or family[c] == fam]
    rec = {"family": fam, "cases": len(sel)}
    for tag, e in (("original", W1), ("prohibition", W1B)):
        a = np.array([per_case[e][c] for c in sel])
        rec[f"{tag}_calls"] = int(a[:, 2].sum())
        rec[f"{tag}_endpoint"] = int(a[:, 0].sum())
        rec[f"{tag}_route_valid"] = int(a[:, 1].sum())
    table.append(rec)

A = np.array([per_case[W1][c] for c in cases], float)
B = np.array([per_case[W1B][c] for c in cases], float)
def diffs(A, B):
    n = A[:, 2].sum()
    return [100 * (B[:, 0].sum() - A[:, 0].sum()) / n, 100 * (B[:, 1].sum() - A[:, 1].sum()) / n]
rng = np.random.default_rng(20261029)
boot = np.array([diffs(A[i], B[i]) for i in (rng.integers(0, 290, 290) for _ in range(10000))])
lo, hi = np.percentile(boot, [2.5, 97.5], axis=0)
point = diffs(A, B)
summary = {
    "endpoint_diff_pp": round(point[0], 2), "endpoint_diff_ci95": [round(lo[0], 2), round(hi[0], 2)],
    "route_valid_diff_pp": round(point[1], 2), "route_valid_diff_ci95": [round(lo[1], 2), round(hi[1], 2)],
    "bootstrap": "10,000 case-cluster resamples of the 290 cases, seed 20261029",
    "difference": "prohibition minus original, as a share of 1,450 calls",
}
OUT.mkdir(parents=True, exist_ok=True)
with (OUT / "prompt_comparison_by_family.csv").open("w", newline="") as h:
    w = csv.DictWriter(h, fieldnames=list(table[0])); w.writeheader(); w.writerows(table)
(OUT / "prompt_comparison_summary.json").write_text(json.dumps(summary, indent=2))

p = table[-1]
macro = {
    "NMIProhibitionEndpointPassCount": p["prohibition_endpoint"],
    "NMIProhibitionRouteValidCount": p["prohibition_route_valid"],
    "NMIProhibitionEndpointPassRate": f"{100*p['prohibition_endpoint']/p['prohibition_calls']:.2f}\\%",
    "NMIProhibitionInvalidCount": p["prohibition_endpoint"] - p["prohibition_route_valid"],
    "NMIPromptEndpointDiffPP": f"{point[0]:.2f}", "NMIPromptEndpointDiffCILow": f"{lo[0]:.2f}", "NMIPromptEndpointDiffCIHigh": f"{hi[0]:.2f}",
    "NMIPromptRouteValidDiffPP": f"{point[1]:.2f}", "NMIPromptRouteValidDiffCILow": f"{lo[1]:.2f}", "NMIPromptRouteValidDiffCIHigh": f"{hi[1]:.2f}",
}
wave = next(t for t in table if t["family"] == "wave")
macro.update({"NMIWaveOriginalEndpoint": wave["original_endpoint"], "NMIWaveOriginalRouteValid": wave["original_route_valid"],
              "NMIWaveProhibitionEndpoint": wave["prohibition_endpoint"], "NMIWaveProhibitionRouteValid": wave["prohibition_route_valid"]})
lines = ["% Generated by scripts/build_prompt_comparison_source.py; do not edit."]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macro.items()]
(ROOT / "Nature/generated/nmi_prompt_comparison_macros.tex").write_text("\n".join(lines) + "\n")
print(json.dumps(summary)); print(table[-1]); print(wave)

passes = [r for r in rows if r["experiment_id"] == W1 and r["endpoint_pass"] == "True"]
assert len(passes) == 1162
with (OUT / "primary_pass_errors.csv").open("w", newline="") as h:
    w = csv.writer(h); w.writerow(["case_id", "run_idx", "family", "route_status", "rel_l2", "tau_acc"])
    for r in passes:
        w.writerow([r["case_id"], r["run_idx"], r["family"], r["route_status"], r["rel_l2"], r["tau_acc"]])
