#!/usr/bin/env python3
"""Write LaTeX macros for the statistical reanalysis and the benchmark-integrity results."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
STATS = ROOT / "analysis/nmi_next_round_20260826/statistical_reanalysis.json"
INTEGRITY = ROOT / "analysis/benchmark_integrity_summary.json"
OUTPUT = ROOT / "Nature/generated/nmi_next_round_macros.tex"

FAMILY_LABELS = {
    "heterogeneous_diffusion": "Heterogeneous diffusion",
    "advection_diffusion_reaction": r"Advection--diffusion--reaction",
    "lshape_poisson": "L-shaped Poisson",
    "coupled_elliptic": "Coupled elliptic",
}


def pp(value: float) -> str:
    return f"{100 * value:.2f}"


def main() -> int:
    stats = json.loads(STATS.read_text(encoding="utf-8"))
    integrity = json.loads(INTEGRITY.read_text(encoding="utf-8"))
    primary = stats["primary_score_inflation"]
    fidelity = primary["specification_fidelity"]
    natural = stats["naturalistic_reference_margins"]
    unaffected = stats["unaffected_primary_sensitivity"]
    scaffold = stats["scaffold_route_readouts"]["paired_two_sided_95_intervals"]
    lines = [
        "% Generated by scripts/generate_nmi_next_round_macros.py; do not edit manually.",
        rf"\newcommand{{\NMIInflationBootstrapCILowPP}}{{{pp(primary['case_cluster_bootstrap_95ci'][0])}}}",
        rf"\newcommand{{\NMIInflationBootstrapCIHighPP}}{{{pp(primary['case_cluster_bootstrap_95ci'][1])}}}",
        rf"\newcommand{{\NMIPrimaryRouteValidCount}}{{{int(primary['observed_route_valid'])}}}",
        rf"\newcommand{{\NMIPrimaryRouteValidRate}}{{{100 * primary['observed_route_valid'] / primary['scheduled']:.2f}\%}}",
        rf"\newcommand{{\NMIClaimSupportingCount}}{{{int(fidelity['claim_supporting_success_count_C_equals_R_times_F'])}}}",
        rf"\newcommand{{\NMIClaimSupportingRate}}{{{100 * fidelity['claim_supporting_success_rate']:.2f}\%}}",
        rf"\newcommand{{\NMIIntegrityAffectedPrimaryCaseCount}}{{{int(fidelity['affected_primary_cases'])}}}",
        rf"\newcommand{{\NMIIntegrityAffectedPrimaryCallCount}}{{{int(fidelity['affected_scheduled_calls'])}}}",
        rf"\newcommand{{\NMIIntegrityAffectedPrimaryEndpointPassCount}}{{{int(fidelity['endpoint_passes_on_affected_cases'])}}}",
        rf"\newcommand{{\NMIIntegrityExcludedRouteValidCount}}{{{int(fidelity['route_valid_endpoint_passes_excluded_by_fidelity'])}}}",
        rf"\newcommand{{\NMIUnaffectedPrimaryCallCount}}{{{int(unaffected['unaffected_calls'])}}}",
        rf"\newcommand{{\NMIUnaffectedEndpointPassCount}}{{{int(unaffected['unaffected_endpoint_passes'])}}}",
        rf"\newcommand{{\NMIUnaffectedEndpointRate}}{{{100 * unaffected['unaffected_endpoint_success_rate']:.2f}\%}}",
        rf"\newcommand{{\NMIUnaffectedRouteValidCount}}{{{int(unaffected['unaffected_route_valid_passes'])}}}",
        rf"\newcommand{{\NMIUnaffectedRouteValidRate}}{{{100 * unaffected['unaffected_route_valid_success_rate']:.2f}\%}}",
        rf"\newcommand{{\NMIUnaffectedScoreGapPP}}{{{unaffected['unaffected_score_gap_percentage_points']:.2f}}}",
        rf"\newcommand{{\NMIIntegrityCurrentRows}}{{{int(integrity['current_submission_bank_rows'])}}}",
        rf"\newcommand{{\NMIIntegrityCurrentDefectCaseCount}}{{{int(integrity['current_submission_unique_case_ids_with_failure'])}}}",
        rf"\newcommand{{\NMIIntegrityCurrentDefectRows}}{{{int(integrity['current_submission_rows_with_failure'])}}}",
        rf"\newcommand{{\NMINaturalisticMedianRho}}{{{natural['median_rho']:.3f}}}",
        rf"\newcommand{{\NMINaturalisticMaximumRho}}{{{natural['maximum_rho']:.3f}}}",
        rf"\newcommand{{\NMINaturalisticRefinementCount}}{{{int(natural['cases_requiring_refinement'])}}}",
        r"\newcommand{\NMINaturalisticRhoRows}{%",
    ]
    for family in FAMILY_LABELS:
        row = natural["family_summary"][family]
        lines.append(
            rf"{FAMILY_LABELS[family]} & {row['cases']} & {row['median_rho']:.3f} & {row['maximum_rho']:.3f} \\"
        )
    lines.extend([r"}", r"\newcommand{\NMIScaffoldRouteIntervalRows}{%"])
    labels = (
        ("prescription_only_minus_full", "Prescription-only $-$ full"),
        ("prescription_only_minus_choice_free", "Prescription-only $-$ choice-free"),
    )
    for key, label in labels:
        rv = scaffold[key]["route_valid"]
        direct = scaffold[key]["direct_return"]
        lines.append(
            rf"{label} & {pp(rv['estimate'])} [{pp(rv['lower'])}, {pp(rv['upper'])}] & "
            rf"{pp(direct['estimate'])} [{pp(direct['lower'])}, {pp(direct['upper'])}] \\"
        )
    pf = scaffold["prescription_only_minus_full"]
    pc = scaffold["prescription_only_minus_choice_free"]
    lines.extend([r"}", r"\newcommand{\NMIScaffoldRouteIntervalMetricRows}{%"])
    lines.append(
        rf"Route-valid difference [95\% CI], pp & "
        rf"{pp(pf['route_valid']['estimate'])} [{pp(pf['route_valid']['lower'])}, {pp(pf['route_valid']['upper'])}] & "
        rf"{pp(pc['route_valid']['estimate'])} [{pp(pc['route_valid']['lower'])}, {pp(pc['route_valid']['upper'])}] \\"
    )
    lines.append(
        rf"Direct-return difference [95\% CI], pp & "
        rf"{pp(pf['direct_return']['estimate'])} [{pp(pf['direct_return']['lower'])}, {pp(pf['direct_return']['upper'])}] & "
        rf"{pp(pc['direct_return']['estimate'])} [{pp(pc['direct_return']['lower'])}, {pp(pc['direct_return']['upper'])}] \\"
    )
    lines.extend([r"}", r"\newcommand{\NMIClassifierSensitivityRows}{%"])
    scenario_labels = {
        "observed": "$p=0$ (observed labels)",
        "one_percent": r"$p=1\%$",
        "sampled_wilson_upper": r"$p=2.91\%$ (Wilson upper bound)",
        "five_percent": r"$p=5\%$",
    }
    for row in primary["classifier_false_negative_scenarios"]:
        lines.append(
            rf"{scenario_labels[row['scenario']]} & {100 * row['route_valid_success_rate']:.2f}\% \\"
        )
    lines.extend([r"}", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
