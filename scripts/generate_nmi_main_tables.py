#!/usr/bin/env python3
"""Write Table 1 and the replay table rows."""

from __future__ import annotations

import csv
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTCOME_DIR = ROOT / "paper" / "source_data" / "fig3_outcome_stage_route_conditioning"
REPLAY_DIR = ROOT / "paper" / "source_data" / "fig4_frozen_program_scientific_replay"
OUTPUT = ROOT / "Nature" / "generated" / "nmi_main_tables.tex"

AXES = ("O", "G", "B", "D", "S", "C")
AGENTS = ("Codex GPT-5.5", "Claude Opus 4.7")
FAMILY_LABELS = {
    "heterogeneous_diffusion": "Heterogeneous diffusion",
    "advection_diffusion_reaction": r"Advection--diffusion--reaction",
    "lshape_poisson": "L-shaped Poisson",
    "coupled_elliptic": "Coupled elliptic",
}


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def fmt(value: str) -> str:
    number = float(value)
    if abs(number) < 0.0005:
        number = 0.0
    return f"{number:.3f}"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    effects_path = OUTCOME_DIR / "three_estimand_main_effects.csv"
    paired_path = OUTCOME_DIR / "paired_agent_difference.csv"
    replay_path = REPLAY_DIR / "family_specification_success.csv"

    effects = rows(effects_path)
    paired = rows(paired_path)
    replay = rows(replay_path)

    effect_lookup = {
        (row["agent"], row["estimand"], row["axis"]): row for row in effects
    }
    paired_lookup = {row["axis"]: row for row in paired}
    assert set(paired_lookup) == set(AXES)
    assert {row["family"] for row in replay} == set(FAMILY_LABELS)

    outcome_lines: list[str] = []
    for axis in AXES:
        codex_all = effect_lookup[(AGENTS[0], "all_accuracy_stage", axis)]
        codex_pass = effect_lookup[(AGENTS[0], "endpoint_passes", axis)]
        claude_all = effect_lookup[(AGENTS[1], "all_accuracy_stage", axis)]
        claude_pass = effect_lookup[(AGENTS[1], "endpoint_passes", axis)]
        delta = paired_lookup[axis]
        outcome_lines.append(
            f"{axis} & {fmt(codex_all['coefficient'])} & {fmt(codex_pass['coefficient'])} "
            f"& {fmt(claude_all['coefficient'])} & {fmt(claude_pass['coefficient'])} "
            f"& {fmt(delta['coefficient_delta'])} [{fmt(delta['ci95_low'])}, {fmt(delta['ci95_high'])}] \\\\"
        )

    replay_columns = ("base", "source_scale", "boundary_data", "resolution", "all_replays")
    replay_lines: list[str] = []
    totals = {column: 0 for column in replay_columns}
    denominator = 0
    for row in replay:
        n = int(row["n"])
        denominator += n
        values = [int(row[column]) for column in replay_columns]
        for column, value in zip(replay_columns, values, strict=True):
            totals[column] += value
        replay_lines.append(
            f"{FAMILY_LABELS[row['family']]} & "
            + " & ".join(f"{value}/{n}" for value in values)
            + r" \\"
        )
    assert denominator == 64
    assert [totals[column] for column in replay_columns] == [34, 34, 36, 50, 34]
    replay_lines.extend(
        [
            r"\midrule",
            "All calls & "
            + " & ".join(f"{totals[column]}/{denominator}" for column in replay_columns)
            + r" \\",
        ]
    )

    source_hashes = ", ".join(
        f"{path.name}={digest(path)}" for path in (effects_path, paired_path, replay_path)
    )
    content = "\n".join(
        [
            "% Generated by scripts/generate_nmi_main_tables.py; do not edit manually.",
            f"% Frozen source SHA-256: {source_hashes}",
            r"\newcommand{\NMIOutcomeStageTableRows}{%",
            *outcome_lines,
            r"}",
            r"\newcommand{\NMIReplayFamilyTableRows}{%",
            *replay_lines,
            r"}",
            "",
        ]
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
